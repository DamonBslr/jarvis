/**
 * Source of the Jarvis browser launcher: a tiny stdio MCP proxy that agent CLIs spawn (under Electron-as-Node)
 * in front of Playwright MCP. Jarvis writes it to <userData>/browser/launcher.cjs at run time, so it needs no
 * bundler entry and no asarUnpack rule of its own. Plain CommonJS, no dependencies.
 *
 * argv: <playwright-mcp cli.js> <persistent profile dir> <comma-separated denied tools | -> [playwright args...]
 *
 * What it does:
 *  1. Profile lease. The first concurrent run takes an exclusive lease on the persistent profile (logins persist).
 *     A run that finds it busy gets a throwaway copy of the profile (same logins, changes discarded), or a fresh
 *     in-memory profile if there is nothing to copy. Two Chromes never fight over one profile lock.
 *  2. Tool policy. Tools denied for this run's autonomy level are removed from tools/list and refused on tools/call
 *     (Codex has no per-call approval prompt for MCP tools, so this is the only gate there).
 *  3. Lifecycle. Closes Playwright gracefully when the agent CLI goes away, then releases the lease and deletes the
 *     copy. If it is killed hard, the stale lease (dead pid) and orphaned copies are cleaned up by the next launch.
 */
export const LAUNCHER_SOURCE = String.raw`'use strict'
// Generated by Jarvis (src/main/tools/browser/launcher.ts) and overwritten on every run. Do not edit.
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawn } = require('node:child_process')

const [cli, profile, denyCsv, ...pwArgs] = process.argv.slice(2)
const deny = new Set(denyCsv && denyCsv !== '-' ? denyCsv.split(',') : [])
const log = (m) => process.stderr.write('[jarvis-browser] ' + m + '\n')

const alive = (pid) => {
  if (!pid) return false
  try { process.kill(pid, 0); return true } catch (e) { return e.code === 'EPERM' }
}

// ---- 1. profile lease -------------------------------------------------------------------------------------------
const leaseFile = profile + '.lease'
const CLONE_PREFIX = 'jarvis-browser-clone-'

function leaseHolder() {
  try {
    const pid = parseInt(fs.readFileSync(leaseFile, 'utf8'), 10)
    if (pid) return alive(pid) ? pid : 0
    // Empty file: a contender is between create and write. Treat as held unless it has been empty for a while.
    return Date.now() - fs.statSync(leaseFile).mtimeMs < 5000 ? -1 : 0
  } catch { return 0 }
}

function acquireLease() {
  fs.mkdirSync(path.dirname(leaseFile), { recursive: true })
  for (let i = 0; i < 3; i++) {
    try {
      fs.writeFileSync(leaseFile, String(process.pid), { flag: 'wx' })
      return true
    } catch (e) {
      if (e.code !== 'EEXIST') { log('lease: ' + e.message); return false }
      if (leaseHolder()) return false
      // Stale lease (holder died). Rename first so only one contender gets to remove it.
      const tmp = leaseFile + '.stale-' + process.pid
      try { fs.renameSync(leaseFile, tmp); fs.rmSync(tmp, { force: true }) } catch {}
    }
  }
  return false
}

function releaseLease() {
  try { if (parseInt(fs.readFileSync(leaseFile, 'utf8'), 10) === process.pid) fs.rmSync(leaseFile, { force: true }) } catch {}
}

// A Chrome still holding the profile (orphan, or someone opened it by hand): SingletonLock -> "<host>-<pid>".
function chromeHolds(dir) {
  try {
    const target = fs.readlinkSync(path.join(dir, 'SingletonLock'))
    return alive(parseInt(target.slice(target.lastIndexOf('-') + 1), 10))
  } catch { return false }
}

// Caches and lock files are not worth copying (and the locks would make the copy look busy).
const SKIP = new Set([
  'SingletonLock', 'SingletonSocket', 'SingletonCookie', 'RunningChromeVersion', 'lockfile', 'LOCK',
  'Cache', 'Code Cache', 'GPUCache', 'DawnGraphiteCache', 'DawnWebGPUCache', 'GrShaderCache', 'GraphiteDawnCache',
  'ShaderCache', 'CacheStorage', 'ScriptCache', 'Crashpad', 'BrowserMetrics', 'component_crx_cache',
  'extensions_crx_cache', 'optimization_guide_model_store', 'Safe Browsing', 'OnDeviceHeadSuggestModel'
])

function sweepClones() {
  try {
    for (const name of fs.readdirSync(os.tmpdir())) {
      if (!name.startsWith(CLONE_PREFIX)) continue
      const pid = parseInt(name.slice(CLONE_PREFIX.length), 10)
      if (pid && !alive(pid)) fs.rmSync(path.join(os.tmpdir(), name), { recursive: true, force: true })
    }
  } catch {}
}

function cloneProfile() {
  if (!fs.existsSync(path.join(profile, 'Default'))) return null
  const dest = path.join(os.tmpdir(), CLONE_PREFIX + process.pid)
  try {
    fs.cpSync(profile, dest, {
      recursive: true,
      verbatimSymlinks: true,
      filter: (p) => !SKIP.has(path.basename(p))
    })
    return dest
  } catch (e) {
    log('could not copy the profile (' + e.message + '), using a fresh one')
    fs.rmSync(dest, { recursive: true, force: true })
    return null
  }
}

sweepClones()
let leased = acquireLease()
if (leased && chromeHolds(profile)) { releaseLease(); leased = false }
let clone = null
const args = [...pwArgs]
if (leased) {
  args.push('--user-data-dir', profile)
} else {
  clone = cloneProfile()
  if (clone) {
    log('the Jarvis browser profile is in use by another run; using a temporary copy (logins kept, changes discarded)')
    args.push('--user-data-dir', clone)
  } else {
    log('the Jarvis browser profile is in use by another run; using a fresh in-memory profile')
    args.push('--isolated')
  }
}

// ---- 2. stdio proxy with tool policy ----------------------------------------------------------------------------
const child = spawn(process.execPath, [cli, ...args], { stdio: ['pipe', 'pipe', 'inherit'], env: process.env })

function eachLine(stream, onLine) {
  let buf = ''
  stream.setEncoding('utf8')
  stream.on('data', (chunk) => {
    let from = buf.length
    buf += chunk
    let i
    while ((i = buf.indexOf('\n', from)) >= 0) {
      const line = buf.slice(0, i)
      buf = buf.slice(i + 1)
      from = 0
      if (line.trim()) onLine(line)
    }
  })
  stream.on('end', () => { if (buf.trim()) onLine(buf); buf = '' })
}

const listIds = new Set()
const toClient = (line) => process.stdout.write(line + '\n')

eachLine(process.stdin, (line) => {
  let msg = null
  try { msg = JSON.parse(line) } catch {}
  if (msg && msg.id != null && msg.method === 'tools/list') listIds.add(msg.id)
  if (msg && msg.id != null && msg.method === 'tools/call' && msg.params && deny.has(msg.params.name)) {
    toClient(JSON.stringify({
      jsonrpc: '2.0',
      id: msg.id,
      result: { isError: true, content: [{ type: 'text', text: msg.params.name + ' is disabled by Jarvis at this autonomy level.' }] }
    }))
    return
  }
  child.stdin.write(line + '\n')
})

eachLine(child.stdout, (line) => {
  if (listIds.size && deny.size && line.length < 4e6) {
    try {
      const msg = JSON.parse(line)
      if (msg && listIds.has(msg.id)) {
        listIds.delete(msg.id)
        if (msg.result && Array.isArray(msg.result.tools)) {
          msg.result.tools = msg.result.tools.filter((t) => !deny.has(t.name))
          return toClient(JSON.stringify(msg))
        }
      }
    } catch {}
  }
  toClient(line)
})

// ---- 3. lifecycle -----------------------------------------------------------------------------------------------
let cleaned = false
function cleanup() {
  if (cleaned) return
  cleaned = true
  if (leased) releaseLease()
  if (clone) {
    try { fs.rmSync(clone, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }) } catch {}
  }
}

let stopping = false
function stop() {
  if (stopping) return
  stopping = true
  child.stdin.end() // Playwright MCP closes the browser and exits when its stdin closes
  setTimeout(() => child.kill('SIGTERM'), 5000).unref()
  setTimeout(() => child.kill('SIGKILL'), 10000).unref()
}

process.stdin.on('end', stop)
process.stdout.on('error', stop)
child.stdin.on('error', () => {})
for (const sig of ['SIGTERM', 'SIGINT', 'SIGHUP']) process.on(sig, stop)
child.on('error', (e) => { log('failed to start Playwright MCP: ' + e.message); cleanup(); process.exit(1) })
child.on('exit', (code, signal) => { cleanup(); process.exit(code == null ? (signal ? 1 : 0) : code) })
process.on('exit', cleanup)
`
